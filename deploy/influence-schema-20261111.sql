CREATE TABLE influence_rule_set (
 rule_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 win_points integer NOT NULL CHECK(win_points>=0),
 claim_points integer NOT NULL CHECK(claim_points>=0),
 policy jsonb NOT NULL CHECK(jsonb_typeof(policy)='object')
);
CREATE TABLE influence_contest (
 contest_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chain_id text NOT NULL,
 start_height bigint NOT NULL CHECK(start_height>0),
 end_height bigint NOT NULL,
 rule_id bigint NOT NULL REFERENCES influence_rule_set,
 CHECK(end_height>=start_height),
 UNIQUE(contest_id,chain_id)
);
-- Rebuilds write a new build, then atomically publish its pointer.
CREATE TABLE influence_projection_build (
 build_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 contest_id bigint NOT NULL,
 chain_id text NOT NULL,
 projected_height bigint NOT NULL CHECK(projected_height>=0),
 state text NOT NULL CHECK(state IN ('building','live','final','invalid')),
 FOREIGN KEY(contest_id,chain_id) REFERENCES influence_contest(contest_id,chain_id),
 UNIQUE(contest_id,build_id), UNIQUE(build_id,chain_id)
) WITH (fillfactor=80);
CREATE TABLE influence_published_build (
 contest_id bigint PRIMARY KEY REFERENCES influence_contest,
 build_id bigint NOT NULL,
 FOREIGN KEY(contest_id,build_id) REFERENCES influence_projection_build(contest_id,build_id)
);

-- Sparse canonical facts: preserve globally unique source identity without
-- adding a timestamp to that identity merely to satisfy hypertable indexing.
CREATE TABLE influence_raid (
 raid_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chain_id text NOT NULL,
 height bigint NOT NULL CHECK(height>0),
 phase smallint NOT NULL CHECK(phase BETWEEN 0 AND 3),
 tx_index integer NOT NULL,
 event_index integer NOT NULL CHECK(event_index>=0),
 attribute_index integer NOT NULL DEFAULT 0 CHECK(attribute_index>=0),
 msg_index integer,
 block_hash text NOT NULL,
 block_time timestamptz NOT NULL,
 attacker text NOT NULL,
 defender text NOT NULL,
 attacker_guild text,
 defender_guild text,
 planet text NOT NULL,
 sector smallint NOT NULL CHECK(sector IN (0,127,999,44)),
 attribution_complete boolean NOT NULL,
 payload_hash text NOT NULL,
 CHECK((phase=2 AND tx_index>=0) OR (phase<>2 AND tx_index=-1)),
 CHECK(msg_index IS NULL OR (phase=2 AND msg_index>=0)),
 UNIQUE(chain_id,height,phase,tx_index,event_index,attribute_index),
 UNIQUE(raid_id,chain_id)
);
CREATE INDEX influence_raid_planet_latest ON influence_raid
 (chain_id,planet,height DESC,phase DESC,tx_index DESC,event_index DESC,attribute_index DESC)
 INCLUDE(raid_id,attacker,defender,sector,attacker_guild,defender_guild,attribution_complete);
CREATE INDEX influence_raid_player_range ON influence_raid(chain_id,attacker,height,planet);
-- No redundant (chain_id,height) index: source-coordinate unique index has it.

CREATE TABLE influence_membership_history (
 chain_id text NOT NULL, player text NOT NULL,
 height bigint NOT NULL CHECK(height>=0),
 phase smallint NOT NULL CHECK(phase BETWEEN 0 AND 3),
 tx_index integer NOT NULL, event_index integer NOT NULL CHECK(event_index>=0),
 attribute_index integer NOT NULL DEFAULT 0 CHECK(attribute_index>=0),
 guild text, baseline boolean NOT NULL DEFAULT false,
 CHECK((phase=2 AND tx_index>=0) OR (phase<>2 AND tx_index=-1)),
 PRIMARY KEY(chain_id,player,height,phase,tx_index,event_index,attribute_index)
);
-- The PK supports backward index scans for exact end-of-block membership.

CREATE TABLE influence_member (
 build_id bigint NOT NULL REFERENCES influence_projection_build,
 player text NOT NULL, guild text,
 PRIMARY KEY(build_id,player)
) WITH(fillfactor=80);
CREATE INDEX influence_member_roster ON influence_member(build_id,guild,player);

CREATE TABLE influence_contest_planet (
 build_id bigint NOT NULL REFERENCES influence_projection_build,
 planet text NOT NULL,
 sector smallint NOT NULL CHECK(sector IN (0,127,999,44)),
 PRIMARY KEY(build_id,planet), UNIQUE(build_id,planet,sector)
);
CREATE TABLE influence_player_planet_win (
 build_id bigint NOT NULL, player text NOT NULL, planet text NOT NULL,
 chain_id text NOT NULL, first_raid_id bigint NOT NULL,
 PRIMARY KEY(build_id,player,planet),
 FOREIGN KEY(build_id,player) REFERENCES influence_member,
 FOREIGN KEY(build_id,planet) REFERENCES influence_contest_planet,
 FOREIGN KEY(build_id,chain_id) REFERENCES influence_projection_build(build_id,chain_id),
 FOREIGN KEY(first_raid_id,chain_id) REFERENCES influence_raid(raid_id,chain_id)
);
CREATE INDEX influence_player_planet_supporters ON influence_player_planet_win(build_id,planet,player);

CREATE TABLE influence_guild_planet_win (
 build_id bigint NOT NULL, guild text NOT NULL, planet text NOT NULL,
 supporter_count bigint NOT NULL CHECK(supporter_count>0),
 PRIMARY KEY(build_id,guild,planet),
 FOREIGN KEY(build_id,planet) REFERENCES influence_contest_planet
) WITH(fillfactor=80,autovacuum_vacuum_scale_factor=0.02,autovacuum_vacuum_threshold=1000);
CREATE INDEX influence_guild_planet_reverse ON influence_guild_planet_win(build_id,planet,guild);
-- supporter_count deliberately has NO index: allow HOT updates when possible.

CREATE TABLE influence_planet_claim (
 build_id bigint NOT NULL, planet text NOT NULL, sector smallint NOT NULL,
 chain_id text NOT NULL, latest_raid_id bigint NOT NULL, holder text,
 PRIMARY KEY(build_id,planet),
 FOREIGN KEY(build_id,planet,sector) REFERENCES influence_contest_planet(build_id,planet,sector),
 FOREIGN KEY(build_id,chain_id) REFERENCES influence_projection_build(build_id,chain_id),
 FOREIGN KEY(latest_raid_id,chain_id) REFERENCES influence_raid(raid_id,chain_id),
 FOREIGN KEY(build_id,holder) REFERENCES influence_member(build_id,player)
) WITH(fillfactor=80);
CREATE INDEX influence_claim_holder ON influence_planet_claim(build_id,holder,sector,planet) WHERE holder IS NOT NULL;
CREATE INDEX influence_claim_sector ON influence_planet_claim(build_id,sector,planet);

CREATE TABLE influence_player_sector (
 build_id bigint NOT NULL, player text NOT NULL,
 sector smallint NOT NULL CHECK(sector IN (0,127,999,44)),
 held_planets bigint NOT NULL CHECK(held_planets>=0),
 PRIMARY KEY(build_id,player,sector),
 FOREIGN KEY(build_id,player) REFERENCES influence_member
) WITH(fillfactor=80);
CREATE TABLE influence_guild_sector (
 build_id bigint NOT NULL REFERENCES influence_projection_build,
 guild text NOT NULL, sector smallint NOT NULL CHECK(sector IN (0,127,999,44)),
 unique_planets bigint NOT NULL CHECK(unique_planets>=0),
 held_planets bigint NOT NULL CHECK(held_planets>=0),
 PRIMARY KEY(build_id,guild,sector)
) WITH(fillfactor=80);
-- Do not index mutable score/count columns for an 18-row scoreboard.

-- Additive, canonical score changes: partition on the API's exact boundary,
-- block height, NOT wall-clock time. Include height in every unique key.
CREATE TABLE influence_score_change (
 build_id bigint NOT NULL REFERENCES influence_projection_build,
 height bigint NOT NULL CHECK(height>0),
 phase smallint NOT NULL CHECK(phase BETWEEN 0 AND 3),
 tx_index integer NOT NULL, event_index integer NOT NULL CHECK(event_index>=0),
 attribute_index integer NOT NULL CHECK(attribute_index>=0),
 leg integer NOT NULL CHECK(leg>=0),
 guild text NOT NULL, sector smallint NOT NULL CHECK(sector IN (0,127,999,44)),
 unique_delta bigint NOT NULL, claim_delta bigint NOT NULL,
 reason text NOT NULL, block_time timestamptz NOT NULL,
 CHECK((phase=2 AND tx_index>=0) OR (phase<>2 AND tx_index=-1)),
 CHECK(unique_delta<>0 OR claim_delta<>0),
 PRIMARY KEY(build_id,height,phase,tx_index,event_index,attribute_index,leg)
);
SELECT create_hypertable('influence_score_change',by_range('height',100000::bigint),create_default_indexes=>false);
CREATE INDEX influence_score_change_subject ON influence_score_change(build_id,guild,sector,height);

-- This installation indexes one chain. Do not attach age-based policies using
-- this clock to mixed-chain heights; use chain-isolated history instead.
CREATE FUNCTION influence_current_height() RETURNS bigint
LANGUAGE sql STABLE AS $$
 SELECT COALESCE(max(projected_height),0)::bigint FROM structs.influence_projection_build
 WHERE state IN ('live','final')
$$;
SELECT set_integer_now_func('influence_score_change','influence_current_height');

CREATE MATERIALIZED VIEW influence_score_change_1000
WITH(timescaledb.continuous,timescaledb.materialized_only=true) AS
 SELECT build_id,guild,sector,time_bucket(1000::bigint,height) AS bucket,
        sum(unique_delta) AS unique_delta,sum(claim_delta) AS claim_delta
 FROM influence_score_change GROUP BY build_id,guild,sector,bucket
WITH NO DATA;
